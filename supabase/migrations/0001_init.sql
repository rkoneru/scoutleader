-- Helper: the troop the current user belongs to. Security definer so the
-- policies below do not recurse through the scouts policy.
create or replace function public.current_troop_id()
returns uuid
language sql
stable
security definer
set search_path = public
as $$
  select troop_id from public.scouts where id = auth.uid();
$$;

-- Troops: a scout can see the troop they are in. No one can select by code,
-- so codes stay unguessable-by-listing.
create policy troops_read_own on public.troops
  for select to authenticated
  using (id = public.current_troop_id());

-- Patrols: readable within your own troop. No writes yet (companion mode).
create policy patrols_read_own_troop on public.patrols
  for select to authenticated
  using (troop_id = public.current_troop_id());

-- Scouts: full control of your own row.
create policy scouts_read_self on public.scouts
  for select to authenticated
  using (id = auth.uid());

-- Scouts: read-only visibility of troop mates, for rosters later. Names and
-- ranks only in practice -- there is nothing sensitive on this table.
create policy scouts_read_troop on public.scouts
  for select to authenticated
  using (troop_id is not null and troop_id = public.current_troop_id());

create policy scouts_insert_self on public.scouts
  for insert to authenticated
  with check (id = auth.uid());

create policy scouts_update_self on public.scouts
  for update to authenticated
  using (id = auth.uid())
  with check (id = auth.uid());

-- Skill profiles: strictly your own. A scout's scores are not troop-visible.
create policy skill_profiles_read_self on public.skill_profiles
  for select to authenticated
  using (scout_id = auth.uid());

create policy skill_profiles_insert_self on public.skill_profiles
  for insert to authenticated
  with check (scout_id = auth.uid());

create policy skill_profiles_update_self on public.skill_profiles
  for update to authenticated
  using (scout_id = auth.uid())
  with check (scout_id = auth.uid());

-- Scenarios: content is readable by any signed-in scout. Writes are service
-- role only (the seed script), so nobody can edit the curriculum from a phone.
create policy scenarios_read_published on public.scenarios
  for select to authenticated
  using (is_published);

-- Attempts: strictly your own.
create policy attempts_read_self on public.scenario_attempts
  for select to authenticated
  using (scout_id = auth.uid());

create policy attempts_insert_self on public.scenario_attempts
  for insert to authenticated
  with check (scout_id = auth.uid());
